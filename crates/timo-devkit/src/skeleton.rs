//! `new` 脚手架（设计 06 §2 与实现注记）。

use std::path::{Path, PathBuf};

use serde_json::json;
use timo_ext::{
    Capabilities, GUI_MANIFEST_SCHEMA, GuiManifest, HOST_API_VERSION, PermissionTier, PluginKind,
    SlotDecl, is_valid_id,
};

/// 生成骨架，返回写出的相对路径。
pub(crate) fn create(
    id: &str,
    dir: Option<&Path>,
    name: Option<&str>,
    slot: &str,
    tool: Option<&str>,
) -> Result<Vec<String>, String> {
    if !is_valid_id(id) {
        return Err(format!(
            "invalid id `{id}`: use lowercase letters, digits, `_` and `-` (max 32)"
        ));
    }
    let tools = match slot {
        "panel" => Vec::new(),
        "toolCard" => {
            let tool = tool
                .map(str::trim)
                .filter(|tool| !tool.is_empty())
                .ok_or("a toolCard skeleton needs --tool <name>")?;
            if tool.chars().count() > 64 {
                return Err("tool name exceeds 64 chars".to_string());
            }
            vec![tool.to_string()]
        }
        other => return Err(format!("unknown slot `{other}`")),
    };
    let dir = dir.map_or_else(|| PathBuf::from(id), Path::to_path_buf);
    if dir.exists() {
        let mut entries = std::fs::read_dir(&dir)
            .map_err(|error| format!("cannot read {}: {error}", dir.display()))?;
        if entries.next().is_some() {
            return Err(format!("{} is not empty", dir.display()));
        }
    }
    std::fs::create_dir_all(&dir)
        .map_err(|error| format!("cannot create {}: {error}", dir.display()))?;

    let name = name.unwrap_or(id);
    let nsh_id = format!("com.timo.{id}");
    let manifest = GuiManifest {
        schema: GUI_MANIFEST_SCHEMA,
        id: id.to_string(),
        kind: PluginKind::Gui,
        name: name.to_string(),
        version: "0.1.0".to_string(),
        nsh_id: Some(nsh_id.clone()),
        entry: "App.tsx".to_string(),
        bundle: "plugin.nshpkg".to_string(),
        source_hash: format!("sha256:{}", "0".repeat(64)),
        bundler: "timo-devkit/0.1".to_string(),
        created_at: None,
        api: Some(HOST_API_VERSION),
        tier: PermissionTier::ReadOnly,
        slots: vec![SlotDecl {
            kind: slot.to_string(),
            title: Some(name.to_string()),
            icon: None,
            order: Some(0),
            tools,
        }],
        queries: Vec::new(),
        actions: Vec::new(),
        tools: Vec::new(),
        capabilities: Capabilities::default(),
    };
    let manifest_text = serde_json::to_string_pretty(&manifest)
        .map_err(|error| format!("cannot serialize the manifest: {error}"))?
        + "\n";
    std::fs::write(dir.join("timo-plugin.json"), manifest_text)
        .map_err(|error| format!("cannot write timo-plugin.json: {error}"))?;

    let nsh = json!({
        "name": name,
        "id": nsh_id,
        "version": "0.1.0",
        "build": 1,
        "capabilities": {
            // 清单 queries/actions 之外的固定通行项（设计 02 实现注记）：主题补丁与看门狗回执。
            "host": ["theme.update", "__pong"],
            "network": { "hosts": [] },
            "webview": { "hosts": [] }
        }
    });
    let nsh_text = serde_json::to_string_pretty(&nsh)
        .map_err(|error| format!("cannot serialize nsh.json: {error}"))?
        + "\n";
    std::fs::write(dir.join("nsh.json"), nsh_text)
        .map_err(|error| format!("cannot write nsh.json: {error}"))?;

    let tsconfig = json!({
        "extends": "./.nsh/tsconfig.json",
        "include": ["**/*.ts", "**/*.tsx"]
    });
    let tsconfig_text = serde_json::to_string_pretty(&tsconfig)
        .map_err(|error| format!("cannot serialize tsconfig.json: {error}"))?
        + "\n";
    std::fs::write(dir.join("tsconfig.json"), tsconfig_text)
        .map_err(|error| format!("cannot write tsconfig.json: {error}"))?;

    let app = if slot == "toolCard" {
        TOOL_CARD_APP
    } else {
        PANEL_APP
    };
    std::fs::write(dir.join("App.tsx"), app)
        .map_err(|error| format!("cannot write App.tsx: {error}"))?;
    std::fs::write(dir.join(".gitignore"), GITIGNORE)
        .map_err(|error| format!("cannot write .gitignore: {error}"))?;
    std::fs::write(dir.join("README.md"), readme(id, name, slot))
        .map_err(|error| format!("cannot write README.md: {error}"))?;

    Ok(vec![
        "timo-plugin.json".to_string(),
        "nsh.json".to_string(),
        "tsconfig.json".to_string(),
        "App.tsx".to_string(),
        ".gitignore".to_string(),
        "README.md".to_string(),
    ])
}

fn readme(id: &str, name: &str, slot: &str) -> String {
    format!(
        "# {name}\n\n\
         Timo GUI plugin (`{slot}` slot, read-only tier), generated by `timo-devkit new {id}`.\n\n\
         ```bash\n\
         timo-devkit check .\n\
         timo-devkit pack . --key keys/release.secret --cert keys/release.cert.json\n\
         ```\n\n\
         `timo-plugin.json` is the Timo manifest; `nsh.json` is the NSH app metadata and grants\n\
         the host functions (`capabilities.host`) the manifest declares.\n"
    )
}

const GITIGNORE: &str = "\
# generated by nsh\n\
.nsh/\n\
# build output\n\
plugin.nshpkg\n\
manifest.json\n\
# signing material: never commit\n\
*.secret\n\
*.cert.json\n";

const PANEL_APP: &str = r#"import { host, mount, signal, Text, View } from "nsh";

// 宿主在启动参数里给出槽位数据（设计 04 §1）。
const params = host.params as {
  slot?: { kind?: string; data?: { title?: string } };
};

// 宿主看门狗每 2s 发 __ping；nsh 0.3.0 没有内置回应，插件必须显式回 __pong（设计 05 §4）。
host.on("__ping", (data: { t?: number }) => {
  host.post("__pong", { t: data?.t });
});

function App() {
  const count = signal(0);
  return (
    <View class="flex-1 items-center justify-center gap-3 bg-background">
      <Text class="text-base font-semibold text-foreground">
        {params.slot?.data?.title ?? "My Plugin"}
      </Text>
      <View
        role="button"
        class="rounded-(--radius) bg-primary px-4 py-2 active:bg-primary/90"
        onPress={() => count.update((value) => value + 1)}
      >
        <Text class="text-primary-foreground">Clicked {count()} times</Text>
      </View>
    </View>
  );
}

mount(App);
"#;

const TOOL_CARD_APP: &str = r#"import { host, mount, Text, View } from "nsh";

// toolCard 的槽位数据：最近一次调用的工具、状态、参数与结果（已脱敏）。
type ToolCardData = {
  toolName?: string;
  status?: string;
  input?: string;
  output?: string;
};

const data = (host.params as { slot?: { data?: ToolCardData } }).slot?.data ?? {};

// 宿主看门狗每 2s 发 __ping；nsh 0.3.0 没有内置回应，插件必须显式回 __pong（设计 05 §4）。
host.on("__ping", (ping: { t?: number }) => {
  host.post("__pong", { t: ping?.t });
});

function App() {
  return (
    <View class="flex-1 gap-1 bg-background px-2 py-1">
      <Text class="text-xs font-semibold text-foreground">
        {data.toolName ?? "tool"}
      </Text>
      <Text class="text-xs text-muted-foreground">{data.status ?? "idle"}</Text>
    </View>
  );
}

mount(App);
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn skeleton_is_checked_by_the_manifest_rules() {
        let root = tempfile::tempdir().unwrap();
        let dir = root.path().join("demo");
        create("demo", Some(&dir), Some("Demo"), "panel", None).unwrap();
        let manifest = GuiManifest::load(&dir.join("timo-plugin.json"))
            .unwrap()
            .unwrap();
        assert_eq!(manifest.id, "demo");
        assert_eq!(manifest.nsh_id.as_deref(), Some("com.timo.demo"));
        assert_eq!(manifest.slots.len(), 1);
        assert_eq!(manifest.slots[0].kind, "panel");
        assert!(dir.join("App.tsx").is_file());
        let nsh: serde_json::Value =
            serde_json::from_str(&std::fs::read_to_string(dir.join("nsh.json")).unwrap()).unwrap();
        assert_eq!(
            nsh["capabilities"]["host"],
            json!(["theme.update", "__pong"])
        );
    }

    #[test]
    fn tool_card_needs_a_tool() {
        let root = tempfile::tempdir().unwrap();
        let dir = root.path().join("cards");
        assert!(create("cards", Some(&dir), None, "toolCard", None).is_err());
        create("cards", Some(&dir), None, "toolCard", Some("read")).unwrap();
        let manifest = GuiManifest::load(&dir.join("timo-plugin.json"))
            .unwrap()
            .unwrap();
        assert_eq!(manifest.slots[0].tools, vec!["read".to_string()]);
    }

    #[test]
    fn non_empty_directory_is_refused() {
        let root = tempfile::tempdir().unwrap();
        std::fs::write(root.path().join("keep.txt"), "x").unwrap();
        assert!(create("demo", Some(root.path()), None, "panel", None).is_err());
    }

    #[test]
    fn invalid_id_is_refused() {
        assert!(create("Bad Id", None, None, "panel", None).is_err());
    }
}
